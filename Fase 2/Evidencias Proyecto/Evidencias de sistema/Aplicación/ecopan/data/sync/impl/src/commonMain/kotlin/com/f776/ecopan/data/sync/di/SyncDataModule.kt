/**
 * `SyncEngine`/`SyncScheduler`/transport/push/pull bindings land here (03 work items 4/5/7's
 * minimal-wiring acceptance criteria). `ConnectivityMonitor` is now the real per-platform actual
 * bound by `PlatformModule` (03 work item 6 -- androidMain `ConnectivityManager`, iosMain
 * `nw_path_monitor_*`, jvmMain `/health` probe). `SyncAuthProvider` now binds the real
 * [DeviceSessionSyncAuthProvider] (auth/bootstrap follow-up work item), reading/refreshing tokens
 * via [DeviceSessionStore] (`:data:tenant:api`, implemented by `:data:tenant:impl`'s `TokenStore`)
 * -- `PushWorker`'s 401→refresh→retry policy (03 §3.4) is unchanged, only the seam behind it.
 *
 * `"backendBaseUrl"` comes from [BuildKonfig], generated by this module's build script. It used to
 * be three hand-written constants in the three `PlatformModule` actuals -- one per place to forget,
 * and only one of them ever correct. It is now a single `http://localhost:8080` for every client,
 * including Android, which reaches the host through `adb reverse` (README §4). Pointing a build at
 * a backend elsewhere is `-Pecopan.backendHost=<host>` rather than a source edit.
 *
 * It is named `backendBaseUrl`, not `syncBaseUrl`, because `:data:tenant:impl` resolves the same
 * binding for its login/enrollment calls. Those used to be a *separate* `"authBaseUrl"` single
 * hardcoded to `localhost` -- which meant fixing the sync host for Android silently left
 * enrollment pointing at the emulator itself. One host, one binding, no way to fix half of it.
 *
 * [PullWorker]'s `appliers` param is populated via `getAll<SyncApplier>()` (03 §1.1 Open Question
 * 5, resolved pragmatically -- see `SyncApplier`'s KDoc in `:data:sync:api` for why the interface
 * itself had to move there instead of staying `internal` here): every `SyncApplier` bound by any
 * *other* Koin module already loaded into the same container (e.g. `:data:inventory:impl`'s
 * `StockMovementSyncApplier`, `:data:tenant:impl`'s `BranchSyncApplier`) is picked up automatically
 * -- `:data:sync` never adds those modules as compile-time dependencies to do it.
 */
val SyncDataModule = module {
    includes(DatabaseModule, DatastoreModule, PlatformModule)

    single<String>(named("backendBaseUrl")) { BuildKonfig.BACKEND_BASE_URL }

    factory { CursorStore(dataStore = get<DataStore<Preferences>>(named("datastore"))) }
    factory { DeviceIdProvider(dataStore = get<DataStore<Preferences>>(named("datastore"))) }

    single<SyncAuthProvider> {
        DeviceSessionSyncAuthProvider(deviceSessionStore = get<DeviceSessionStore>(), httpClient = get(), baseUrl = get(named("backendBaseUrl")))
    }

    single {
        HttpClient {
            install(ContentNegotiation) {
                json(Json { ignoreUnknownKeys = true })
            }
            // Needed by KtorSyncEventStream. Reconnection is handled there, not by the plugin --
            // see that class's KDoc for why a fixed attempt budget is the wrong policy here.
            install(SSE)
        }
    }

    single<SyncEventStream> {
        KtorSyncEventStream(httpClient = get(), baseUrl = get(named("backendBaseUrl")), authProvider = get())
    }

    factory<SyncTransport> {
        KtorSyncTransport(httpClient = get(), baseUrl = get(named("backendBaseUrl")), authProvider = get())
    }

    factory {
        val deviceIdProvider: DeviceIdProvider = get()
        PushWorker(
            outboxDao = get(),
            transport = get(),
            authProvider = get(),
            deviceIdProvider = { deviceIdProvider.get() },
        )
    }

    factory {
        PullWorker(
            transport = get(),
            cursorStore = get(),
            database = get(),
            appliers = getAll<SyncApplier>(),
            authProvider = get(),
        )
    }

    single {
        SyncEngineImpl(
            pushWorker = get(),
            pullWorker = get(),
            outboxDao = get(),
            connectivityMonitor = get(),
            cursorStore = get(),
            scope = get(named("ioCoroutineScope")),
        )
    }.bind<SyncEngine>()

    single {
        SyncSchedulerImpl(
            syncEngine = get(),
            connectivityMonitor = get(),
            outboxDao = get(),
            scope = get(named("ioCoroutineScope")),
        )
    }.bind<SyncScheduler>()

    singleOf(::RejectedOperationsImpl).bind<RejectedOperations>()
}
