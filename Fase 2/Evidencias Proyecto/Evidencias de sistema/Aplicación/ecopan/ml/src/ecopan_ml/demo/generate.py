"""Synthetic sales generator — DEMO ONLY, NEVER EVALUATED ON (plan 08 §6).

--- Read this before using anything in this file ------------------------------------------------

Evaluating a model on synthetic data is circular. The generator below puts a weekly cycle, a
weekend lift and some noise into the series; a model that "discovers" those is discovering the
assumptions we typed in. Any accuracy number from it measures the generator, not the world, and
quoting one would invalidate the whole evaluation argument.

So this data exists for exactly one purpose: making the *live demo* show something. The stage
walkthrough needs a dashboard with populated charts to demonstrate that sales → sync → forecast →
dashboard is wired end to end. That is a plumbing demonstration, and synthetic data is fine for it
precisely because no claim about accuracy is attached.

Three enforcement mechanisms, because a comment is not enforcement:

  1. Output goes to `data/demo/`, a directory no `eval/` or `train.py` path ever reads.
  2. Every generated file carries a `DEMO DATA` header.
  3. `tests/test_demo_quarantine.py` asserts the training config's paths and the demo output path
     are disjoint, so wiring them together fails the build rather than a defence.

--- What it models, and why those choices ------------------------------------------------------

The generator is a small, explicit model of bakery demand -- readable at a glance, which matters
because its assumptions are exactly what a reviewer should be able to dismiss:

    demand(d) = base(branch, product_type)
              × weekday_multiplier(dow)
              × (1 + seasonal_amplitude · sin(2π · day_of_year / 365))
              × holiday_multiplier(d)
              + noise

`base` differs per (branch, product_type) so the demo has series of visibly different scale.
`weekday_multiplier` peaks at the weekend, which is the dominant real pattern in bakery retail.
Noise is **negative binomial**, not Gaussian: counts cannot go negative, and real demand is
over-dispersed (variance exceeds the mean) in a way Poisson cannot represent. Using a Gaussian
would produce impossible negative days that then have to be clipped, which distorts the low-volume
series most.
"""

import json
from dataclasses import dataclass, field
from datetime import date, timedelta
from pathlib import Path

import numpy as np

DEMO_HEADER = "DEMO DATA — synthetic, generated by ecopan_ml.demo.generate. NEVER for evaluation."

# Mirrors the Spanish reference tenant seeded by the backend (plan 11).
DEFAULT_PRODUCT_TYPES = ("Pan", "Pastelería")
DEFAULT_BRANCHES = ("Sucursal Principal", "Sucursal Providencia")

WEEKDAY_MULTIPLIER = {
    0: 0.95,  # Monday — slow start
    1: 0.92,
    2: 0.95,
    3: 1.00,
    4: 1.18,  # Friday — weekend shopping begins
    5: 1.45,  # Saturday — the peak
    6: 1.10,  # Sunday — shorter hours
}


@dataclass
class DemoConfig:
    """Every knob, so a generated dataset is reproducible from this object plus the seed."""

    start: date = date(2026, 1, 1)
    days: int = 365
    branches: tuple[str, ...] = DEFAULT_BRANCHES
    product_types: tuple[str, ...] = DEFAULT_PRODUCT_TYPES
    base_demand: dict[str, float] = field(
        default_factory=lambda: {"Pan": 320.0, "Pastelería": 85.0}
    )
    branch_scale: dict[str, float] = field(
        default_factory=lambda: {"Sucursal Principal": 1.0, "Sucursal Providencia": 0.62}
    )
    seasonal_amplitude: float = 0.12
    # Over-dispersion: variance = mean + mean²/dispersion. Smaller = noisier. 12 gives visible
    # day-to-day variation without drowning the weekly pattern the demo is meant to show.
    dispersion: float = 12.0
    holidays: tuple[date, ...] = ()
    holiday_multiplier: float = 1.6
    seed: int = 20260101


def _negative_binomial(rng: np.random.Generator, mean: float, dispersion: float) -> int:
    """Draw an over-dispersed non-negative count with the given mean.

    numpy parameterises the negative binomial as (n successes, p). Converting from a mean/dispersion
    parameterisation: p = dispersion / (dispersion + mean), n = dispersion. Then E[X] = mean and
    Var[X] = mean + mean²/dispersion -- strictly greater than the mean, which is the over-dispersion
    real count data shows and Poisson (Var = mean) cannot produce.
    """
    if mean <= 0:
        return 0
    probability = dispersion / (dispersion + mean)
    return int(rng.negative_binomial(dispersion, probability))


def generate(config: DemoConfig | None = None) -> list[dict]:
    """Produce daily demand rows for every (branch, product_type).

    Fully determined by `config.seed`: the same seed yields byte-identical output, which is what
    lets the demo be rehearsed and lets a seeded dataset be regenerated rather than committed.
    """
    config = config or DemoConfig()
    rng = np.random.default_rng(config.seed)
    holidays = set(config.holidays)

    rows: list[dict] = []
    for offset in range(config.days):
        day = config.start + timedelta(days=offset)
        seasonal = 1.0 + config.seasonal_amplitude * np.sin(
            2 * np.pi * day.timetuple().tm_yday / 365.0
        )
        weekday = WEEKDAY_MULTIPLIER[day.weekday()]
        holiday = config.holiday_multiplier if day in holidays else 1.0

        for branch in config.branches:
            for product_type in config.product_types:
                mean = (
                    config.base_demand.get(product_type, 100.0)
                    * config.branch_scale.get(branch, 1.0)
                    * weekday
                    * seasonal
                    * holiday
                )
                rows.append(
                    {
                        "branch": branch,
                        "product_type": product_type,
                        "day": day.isoformat(),
                        "demand": _negative_binomial(rng, mean, config.dispersion),
                        "is_holiday": int(day in holidays),
                    }
                )

    return rows


def write(rows: list[dict], output_path: Path, *, config: DemoConfig) -> Path:
    """Write rows as JSON with the quarantine header embedded in the document itself.

    The header is a real key in the JSON rather than a comment, so it survives being read,
    re-serialised and passed around -- anything that later ingests this file can see what it is.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    document = {
        "_warning": DEMO_HEADER,
        "generator": "ecopan_ml.demo.generate",
        "seed": config.seed,
        "start": config.start.isoformat(),
        "days": config.days,
        "rows": rows,
    }
    output_path.write_text(json.dumps(document, indent=2, ensure_ascii=False), encoding="utf-8")
    return output_path


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description=DEMO_HEADER)
    parser.add_argument("--out", type=Path, default=Path("data/demo/demo_sales.json"))
    parser.add_argument("--seed", type=int, default=DemoConfig.seed)
    parser.add_argument("--days", type=int, default=DemoConfig.days)
    args = parser.parse_args()

    config = DemoConfig(seed=args.seed, days=args.days)
    rows = generate(config)
    path = write(rows, args.out, config=config)
    print(f"{DEMO_HEADER}\nwrote {len(rows):,} rows -> {path}")


if __name__ == "__main__":
    main()
